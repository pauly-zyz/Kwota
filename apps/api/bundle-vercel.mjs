// Bundle the API into a single CommonJS file served by Vercel Functions at /api.
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
await build({
  entryPoints: [path.join(root, "apps/api/src/vercel.ts")],
  outfile: path.join(root, "api/index.js"),
  bundle: true,
  platform: "node",
  target: "node20",
  format: "cjs",
  minify: true,
  sourcemap: false,
  legalComments: "none",
  // migrate.ts' CLI check reads import.meta.url at load time; give it a harmless value in CJS
  define: { "import.meta.url": JSON.stringify("file:///var/task/api/index.js") },
  external: ["pino-pretty"],
  logLevel: "warning",
  banner: { js: "/* KWOTA API — generated by apps/api/bundle-vercel.mjs; do not edit */" },
});
console.log("api/index.js written");
